-- Licence plans and their prices move from the code into the database, so the Motor Movers team can change
-- them. A price change is a new row that applies from a date; past rows are never rewritten, so invoices and
-- licences keep the price they were sold at. Each licence also records the price agreed with the school.

CREATE TABLE licence_plan (
    code        VARCHAR(30)  PRIMARY KEY,
    label       VARCHAR(100) NOT NULL,
    free_trial  BOOLEAN      NOT NULL DEFAULT FALSE,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order  INT          NOT NULL
);

