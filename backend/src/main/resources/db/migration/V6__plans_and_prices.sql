    ('EARLY_YEARS',    'Early years',    FALSE, TRUE, 2),
    ('PRIMARY_CORE',   'Primary core',   FALSE, TRUE, 3),
    ('FULL_PROGRAMME', 'Full programme', FALSE, TRUE, 4),
    ('TRUST',          'Trust',          FALSE, TRUE, 5),
    ('FREE',           'Free',           FALSE, TRUE, 6);

CREATE TABLE licence_plan_price (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_code           VARCHAR(30)  NOT NULL REFERENCES licence_plan (code),
    annual_price_pence  INT          NOT NULL CHECK (annual_price_pence >= 0),
    effective_from      DATE         NOT NULL,
    changed_by          VARCHAR(200) NOT NULL,
    changed_at          TIMESTAMP    NOT NULL,
    UNIQUE (plan_code, effective_from)
);

