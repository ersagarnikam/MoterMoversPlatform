-- Pat's two assessments (docs/assessment-design.md): the developmental milestone charts and the 1 to 4 exercise
-- scores. The charts and exercises are programme content, loaded from src/main/resources/assessment on start-up.
-- Children's rows are deleted with the child.

CREATE TABLE milestone (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chart            VARCHAR(10)  NOT NULL,
    position         INT          NOT NULL,
    band             VARCHAR(40)  NOT NULL,
    age_from_months  INT          NOT NULL,
    age_to_months    INT          NOT NULL,
    description      VARCHAR(400) NOT NULL,
    UNIQUE (chart, position)
);

-- A movement the child can do confidently and securely: once secure, it stays secure.
CREATE TABLE milestone_achievement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     VARCHAR(64)  NOT NULL UNIQUE,
    child_id      BIGINT       NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    milestone_id  BIGINT       NOT NULL REFERENCES milestone (id),
    age_months    INT          NOT NULL,
    year_point    VARCHAR(10)  NOT NULL,
    school_year   INT          NOT NULL,
    achieved_on   DATE         NOT NULL,
    recorded_by   VARCHAR(200) NOT NULL,
    UNIQUE (child_id, milestone_id)
);
CREATE INDEX idx_milestone_achievement_child ON milestone_achievement (child_id);

-- The dated comment boxes under each chart: one per chart, school year and point in the year.
CREATE TABLE development_comment (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id     BIGINT        NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    chart        VARCHAR(10)   NOT NULL,
    school_year  INT           NOT NULL,
    year_point   VARCHAR(10)   NOT NULL,
    note         VARCHAR(2000) NOT NULL,
    written_on   DATE          NOT NULL,
    recorded_by  VARCHAR(200)  NOT NULL,
    UNIQUE (child_id, chart, school_year, year_point)
);

CREATE TABLE exercise (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage         VARCHAR(20)   NOT NULL,
    number        INT           NOT NULL,
    title         VARCHAR(200)  NOT NULL,
    instructions  VARCHAR(4000) NOT NULL,
    UNIQUE (stage, number)
);

-- The four descriptions (1 Not yet, 2 Developing, 3 Nearly there, 4 Confident and accurate). A missing one has no row.
CREATE TABLE exercise_level (
    exercise_id  BIGINT        NOT NULL REFERENCES exercise (id) ON DELETE CASCADE,
    score        INT           NOT NULL,
    description  VARCHAR(1000) NOT NULL,
    PRIMARY KEY (exercise_id, score)
);

-- When an exercise is assessed: START, MODULE_1 to MODULE_n (the end of each module it is in) and END (of the colour).
CREATE TABLE exercise_point (
    exercise_id  BIGINT      NOT NULL REFERENCES exercise (id) ON DELETE CASCADE,
    position     INT         NOT NULL,
    point        VARCHAR(20) NOT NULL,
    PRIMARY KEY (exercise_id, point)
);

-- A later score at the same point replaces the earlier one.
CREATE TABLE exercise_score (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    VARCHAR(64)  NOT NULL UNIQUE,
    child_id     BIGINT       NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    exercise_id  BIGINT       NOT NULL REFERENCES exercise (id),
    point        VARCHAR(20)  NOT NULL,
    score        INT          NOT NULL,
    assessed_on  DATE         NOT NULL,
    recorded_by  VARCHAR(200) NOT NULL,
    UNIQUE (child_id, exercise_id, point)
);
CREATE INDEX idx_exercise_score_child ON exercise_score (child_id);

-- Pat's summary sheet for a colour: two comments (the totals are worked out from the scores).
CREATE TABLE colour_summary (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id          BIGINT        NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    stage             VARCHAR(20)   NOT NULL,
    personal_comment  VARCHAR(2000),
    academic_comment  VARCHAR(2000),
    written_on        DATE          NOT NULL,
    recorded_by       VARCHAR(200)  NOT NULL,
    UNIQUE (child_id, stage)
);
