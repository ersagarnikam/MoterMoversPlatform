-- Short quizzes between a course's live sessions. A quiz opens once the live session it follows has started;
-- learners may retake it, and with quizzes on a course every one must be passed before the certificate.
CREATE TABLE course_quiz (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id      BIGINT       NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    after_session  INT          NOT NULL CHECK (after_session > 0),
    title          VARCHAR(200) NOT NULL,
    pass_percent   INT          NOT NULL CHECK (pass_percent BETWEEN 1 AND 100)
);
CREATE INDEX idx_course_quiz_course ON course_quiz (course_id);

-- Options are stored one per line; correct_option counts from 0.
CREATE TABLE quiz_question (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id         BIGINT        NOT NULL REFERENCES course_quiz (id) ON DELETE CASCADE,
    position        INT           NOT NULL,
    text            VARCHAR(500)  NOT NULL,
    options         VARCHAR(2000) NOT NULL,
    correct_option  INT           NOT NULL CHECK (correct_option >= 0)
);
CREATE INDEX idx_quiz_question_quiz ON quiz_question (quiz_id);

CREATE TABLE quiz_attempt (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id        BIGINT    NOT NULL REFERENCES course_quiz (id) ON DELETE CASCADE,
    enrolment_id   BIGINT    NOT NULL REFERENCES enrolment (id) ON DELETE CASCADE,
    score_percent  INT       NOT NULL,
    passed         BOOLEAN   NOT NULL,
    taken_at       TIMESTAMP NOT NULL
);
CREATE INDEX idx_quiz_attempt_enrolment ON quiz_attempt (enrolment_id);

-- When the learner was reminded that their certificate expires soon, so it goes once.
ALTER TABLE enrolment ADD COLUMN expiry_reminder_sent_on DATE;
