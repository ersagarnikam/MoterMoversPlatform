-- Motor Movers at Home: the 12-month family pass (go-live task 26).

-- The pass price, dated like licence plan prices: a change applies from today or later. No row: not on sale yet.
CREATE TABLE home_pass_price (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_pence     INT          NOT NULL,
    effective_from  DATE         NOT NULL UNIQUE,
    changed_by      VARCHAR(200) NOT NULL,
    changed_at      TIMESTAMP    NOT NULL
);

-- One row per pass bought (payment_id) or extension by the team (no payment). A row bought by card has no dates
-- until Stripe says it is paid. A family's pass runs on a day when one of its rows covers that day.
CREATE TABLE home_pass (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id   BIGINT       NOT NULL REFERENCES family (id) ON DELETE CASCADE,
    payment_id  BIGINT       UNIQUE REFERENCES payment (id),
    starts_on   DATE,
    ends_on     DATE,
    added_by    VARCHAR(200) NOT NULL,
    added_at    TIMESTAMP    NOT NULL,
    note        VARCHAR(300)
);
CREATE INDEX home_pass_family ON home_pass (family_id);

-- Reminders sent before a pass ends (30 and 7 days) and on the day, once each for that end date.
CREATE TABLE home_pass_reminder (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id    BIGINT  NOT NULL REFERENCES family (id) ON DELETE CASCADE,
    ends_on      DATE    NOT NULL,
    days_before  INT     NOT NULL,
    sent_on      DATE    NOT NULL,
    UNIQUE (family_id, ends_on, days_before)
);
