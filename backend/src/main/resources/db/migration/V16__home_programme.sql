-- Motor Movers at Home (docs/home-programme-design.md): a family's own children, not linked to a school. A child now
-- belongs to a school class or to a family. Pat's assessment tables (V15) are shared: a home child's chart
-- answers and exercise ratings live there too, and are deleted with the child.

CREATE TABLE family (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP NOT NULL
);

-- The parents and carers who share a family's children. OWNER started it and can remove others.
CREATE TABLE family_member (
    family_id  BIGINT      NOT NULL REFERENCES family (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role       VARCHAR(10) NOT NULL,
    joined_at  TIMESTAMP   NOT NULL,
    PRIMARY KEY (family_id, user_id),
    UNIQUE (user_id)
);

-- A code a parent gives a second carer to join the family. Works once.
CREATE TABLE family_invite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id    BIGINT       NOT NULL REFERENCES family (id) ON DELETE CASCADE,
    code         VARCHAR(16)  NOT NULL UNIQUE,
    created_by   BIGINT       NOT NULL,
    expires_on   DATE         NOT NULL,
    redeemed_by  BIGINT,
    redeemed_at  TIMESTAMP
);

ALTER TABLE child ALTER COLUMN school_class_id DROP NOT NULL;
ALTER TABLE child ADD COLUMN family_id BIGINT REFERENCES family (id) ON DELETE CASCADE;
-- A home child's age in months on a given day; no date of birth is held.
ALTER TABLE child ADD COLUMN age_months INT;
ALTER TABLE child ADD COLUMN age_recorded_on DATE;
-- When the parent last did the starting check (it is suggested again every few months).
ALTER TABLE child ADD COLUMN home_check_on DATE;
ALTER TABLE child ADD CONSTRAINT ck_child_owner CHECK (school_class_id IS NOT NULL OR family_id IS NOT NULL);
CREATE INDEX idx_child_family ON child (family_id);

-- A daily home session done with Pat's exercises. Keeps counting after the child is linked to a school.
CREATE TABLE home_programme_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    VARCHAR(64)  NOT NULL UNIQUE,
    child_id     BIGINT       NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    stage        VARCHAR(20)  NOT NULL,
    done_on      DATE         NOT NULL,
    recorded_by  VARCHAR(200) NOT NULL
);
CREATE INDEX idx_home_programme_session_child ON home_programme_session (child_id);
