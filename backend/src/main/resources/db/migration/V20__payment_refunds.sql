-- Refunds, whole or part, each with its credit note. A paid payment stays paid; its refunds say how much went back.
-- Numbers come from one counter row, taken inside the transaction that saves the refund, so a refund that fails leaves
-- no gap. stripe_refund_id is unique so a refund Stripe tells us about twice is recorded once.
CREATE TABLE credit_note_counter (
    id           INT PRIMARY KEY,
    last_number  INT NOT NULL
);

INSERT INTO credit_note_counter (id, last_number) VALUES (1, 0);

CREATE TABLE payment_refund (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          BIGINT       NOT NULL REFERENCES payment (id),
    amount_pence        INT          NOT NULL,
    tax_pence           INT,
    reason              VARCHAR(500) NOT NULL,
    refunded_on         DATE         NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    recorded_by         VARCHAR(200) NOT NULL,
    recorded_at         TIMESTAMP    NOT NULL,
    stripe_refund_id    VARCHAR(100) UNIQUE,
    client_id           VARCHAR(64)  UNIQUE,
    credit_note_number  INT          NOT NULL UNIQUE
);

CREATE INDEX idx_payment_refund_payment ON payment_refund (payment_id);
