-- The one-hour induction every member of school staff completes before running sessions, nursery rhymes
-- for the Red, Orange and Yellow stages, and the resource library (rhyme recordings, the rhyme book,
-- printables). All of it goes through the same sign-off and wording check as class sessions.

CREATE TABLE induction_lesson (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position     INT           NOT NULL UNIQUE,
    title        VARCHAR(200)  NOT NULL,
    summary      VARCHAR(500)  NOT NULL,
    body         VARCHAR(8000) NOT NULL,
    minutes      INT           NOT NULL,
    video_url    VARCHAR(500),
    status       VARCHAR(20)   NOT NULL,
    reviewed_by  VARCHAR(200),
    reviewed_at  TIMESTAMP
);

CREATE TABLE induction_progress (
    user_id       BIGINT    NOT NULL REFERENCES app_user (id),
    lesson_id     BIGINT    NOT NULL REFERENCES induction_lesson (id) ON DELETE CASCADE,
    completed_at  TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, lesson_id)
);

-- Set once, when the last approved lesson is done. Lessons added later do not lock anyone out.
ALTER TABLE app_user ADD COLUMN induction_completed_on DATE;

CREATE TABLE library_resource (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(20)   NOT NULL,
    title        VARCHAR(200)  NOT NULL,
    description  VARCHAR(500)  NOT NULL,
    stage        VARCHAR(20),
    file_url     VARCHAR(500),
    words        VARCHAR(4000),
    status       VARCHAR(20)   NOT NULL,
    reviewed_by  VARCHAR(200),
    reviewed_at  TIMESTAMP
);

ALTER TABLE programme_session ADD COLUMN rhyme_id BIGINT REFERENCES library_resource (id);
