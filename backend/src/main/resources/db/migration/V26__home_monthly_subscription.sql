-- The Programme at Home is billed monthly (go-live task 68): a Stripe subscription per family. Each month Stripe
-- takes is a payment here and a home_pass row for the days it covers, so the gate on sessions is unchanged.

-- The monthly price, dated like the pass price. No row in force: monthly is not on sale. A change applies to new
-- subscriptions only; a family keeps the price it subscribed at.
CREATE TABLE home_monthly_price (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_pence     INT          NOT NULL,
    effective_from  DATE         NOT NULL UNIQUE,
    changed_by      VARCHAR(200) NOT NULL,
    changed_at      TIMESTAMP    NOT NULL
);

-- One row per subscription a family starts. PENDING until Stripe says the first month is paid (its Checkout page is
-- reused while it is open), then ACTIVE, PAST_DUE while a month's payment has failed, and ENDED. A family has at most
-- one that is ACTIVE or PAST_DUE (kept in the code, under a lock on the family's row).
CREATE TABLE home_subscription (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id               BIGINT        NOT NULL REFERENCES family (id) ON DELETE CASCADE,
    payer_id                BIGINT        NOT NULL REFERENCES app_user (id),
    price_pence             INT           NOT NULL,
    status                  VARCHAR(20)   NOT NULL,
    stripe_session_id       VARCHAR(200),
    checkout_url            VARCHAR(2000),
    checkout_expires_at     TIMESTAMP,
    stripe_subscription_id  VARCHAR(200)  UNIQUE,
    stripe_customer_id      VARCHAR(200),
    -- Will end when the paid month does (the payer or the team cancelled).
    cancelling              BOOLEAN       NOT NULL DEFAULT FALSE,
    -- The family has been told the last day, once.
    end_notice_sent         BOOLEAN       NOT NULL DEFAULT FALSE,
    -- The invoice whose failed payment the payer was last told about, so each is told once.
    failed_invoice_id       VARCHAR(200),
    created_at              TIMESTAMP     NOT NULL,
    ended_at                TIMESTAMP,
    cancelled_by            VARCHAR(200),
    cancel_note             VARCHAR(300)
);
CREATE INDEX home_subscription_family ON home_subscription (family_id);

-- The month a pass row covers, when it came from a subscription: such a row renews, so it gets no ending reminders.
ALTER TABLE home_pass ADD COLUMN subscription_id BIGINT REFERENCES home_subscription (id) ON DELETE CASCADE;

-- Stripe's invoice for a month of a subscription, so each invoice is recorded once.
ALTER TABLE payment ADD COLUMN stripe_invoice_id VARCHAR(200);
ALTER TABLE payment ADD CONSTRAINT payment_stripe_invoice UNIQUE (stripe_invoice_id);
