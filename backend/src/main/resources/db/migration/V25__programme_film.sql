-- The programme's films (go-live task 57). A film belongs to one rhyme or module of a colour (stage and unit), where
-- every session of it plays the film, or to one exercise of a colour's grid, where each step of a session plays its
-- own. They are kept here, not on the sessions, so sessions added later (as when the session plans load) have them
-- too. A session's own film wins over its rhyme's or module's.
CREATE TABLE programme_film (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage       VARCHAR(20)  NOT NULL,
    unit        INT,
    exercise_id BIGINT REFERENCES exercise (id),
    video_url   VARCHAR(500),
    video_key   VARCHAR(200),
    credit      VARCHAR(200),
    attached_by VARCHAR(255) NOT NULL,
    attached_at TIMESTAMP    NOT NULL,
    CONSTRAINT uq_programme_film_unit UNIQUE (stage, unit),
    CONSTRAINT uq_programme_film_exercise UNIQUE (exercise_id),
    CONSTRAINT ck_programme_film_target CHECK ((unit IS NULL AND exercise_id IS NOT NULL)
        OR (unit IS NOT NULL AND exercise_id IS NULL))
);
