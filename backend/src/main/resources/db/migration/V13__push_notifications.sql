-- Phones registered for notifications from the parent app (Expo push tokens). A token Expo reports as no longer
-- registered is deleted when a send fails with DeviceNotRegistered.
CREATE TABLE push_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    token       VARCHAR(200) NOT NULL UNIQUE,
    platform    VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);
CREATE INDEX idx_push_token_user ON push_token (user_id);

