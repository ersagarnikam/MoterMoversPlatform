-- Payments the Motor Movers team records: school licence invoices, course fees paid by parents and
-- practitioners, and anything else. Online payment is not integrated; the team enters what was invoiced
-- and marks it paid. Each payment has one payer: a school or a person.

CREATE TABLE payment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id     BIGINT       REFERENCES school (id),
    payer_id      BIGINT       REFERENCES app_user (id),
    purpose       VARCHAR(20)  NOT NULL,
    description   VARCHAR(200) NOT NULL,
    amount_pence  INT          NOT NULL CHECK (amount_pence > 0),
    status        VARCHAR(20)  NOT NULL,
    invoiced_on   DATE         NOT NULL,
    paid_on       DATE,
    reference     VARCHAR(100),
    recorded_by   VARCHAR(200) NOT NULL,
    recorded_at   TIMESTAMP    NOT NULL,
    CHECK ((school_id IS NULL) <> (payer_id IS NULL))
);

CREATE INDEX idx_payment_school ON payment (school_id);
CREATE INDEX idx_payment_payer ON payment (payer_id);
