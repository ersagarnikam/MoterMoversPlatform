-- Accounts for go-live: staff accounts can be switched off, and one-time links let people set or reset
-- a password (staff invites and "forgot password"). Only a hash of each link's token is stored.

ALTER TABLE app_user ADD COLUMN enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE password_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    purpose     VARCHAR(20) NOT NULL,
    created_at  TIMESTAMP   NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    used_at     TIMESTAMP
);
CREATE INDEX idx_password_token_user ON password_token (user_id);
