-- Recorded courses in place of live Zoom courses (go-live task 89; Pat, 2026-11-26). A course is a set of ordered
-- lessons, each a film with optional text and slides; a learner has a place on the course itself, with no cohort,
-- and does the lessons in order. Live cohorts, their sessions and trainers stay, behind a setting that is off.

-- A lesson of a recorded course, written and approved by the team like an induction lesson. The film and the slides
-- are each a pasted https link or an uploaded file's key (a key wins).
CREATE TABLE course_lesson (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id    BIGINT        NOT NULL REFERENCES course (id) ON DELETE CASCADE,
    position     INT           NOT NULL CHECK (position > 0),
    title        VARCHAR(200)  NOT NULL,
    -- Plain text, for example the script; paragraphs are separated by a blank line. May be empty.
    body         TEXT          NOT NULL,
    minutes      INT           NOT NULL CHECK (minutes > 0),
    video_url    VARCHAR(500),
    video_key    VARCHAR(300),
    slides_url   VARCHAR(500),
    slides_key   VARCHAR(300),
    status       VARCHAR(20)   NOT NULL,
    reviewed_by  VARCHAR(200),
    reviewed_at  TIMESTAMP
);
CREATE INDEX idx_course_lesson_course ON course_lesson (course_id, position);

-- A place now belongs to a course; the cohort is there only for a live course.
ALTER TABLE enrolment ADD COLUMN course_id BIGINT REFERENCES course (id);
UPDATE enrolment e SET course_id = (SELECT c.course_id FROM cohort c WHERE c.id = e.cohort_id);
ALTER TABLE enrolment ALTER COLUMN course_id SET NOT NULL;
ALTER TABLE enrolment ALTER COLUMN cohort_id DROP NOT NULL;
CREATE INDEX idx_enrolment_course_user ON enrolment (course_id, user_id);

ALTER TABLE course_request ADD COLUMN course_id BIGINT REFERENCES course (id) ON DELETE CASCADE;
UPDATE course_request r SET course_id = (SELECT c.course_id FROM cohort c WHERE c.id = r.cohort_id);
ALTER TABLE course_request ALTER COLUMN course_id SET NOT NULL;
ALTER TABLE course_request ALTER COLUMN cohort_id DROP NOT NULL;

-- A lesson a learner has done, for their place on the course.
CREATE TABLE course_lesson_progress (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrolment_id  BIGINT    NOT NULL REFERENCES enrolment (id) ON DELETE CASCADE,
    lesson_id     BIGINT    NOT NULL REFERENCES course_lesson (id) ON DELETE CASCADE,
    completed_at  TIMESTAMP NOT NULL,
    UNIQUE (enrolment_id, lesson_id)
);
