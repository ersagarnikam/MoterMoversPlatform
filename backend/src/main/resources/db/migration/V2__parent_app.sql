-- Parent app: school-issued invites link a parent account to a child, approved home activities and
-- guidance articles, and each parent's own log of home sessions.

-- Off by default: a school opts in before any parent can be linked to a child.
ALTER TABLE school ADD COLUMN parent_links_enabled BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE parent_invite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id     BIGINT       NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    code         VARCHAR(16)  NOT NULL UNIQUE,
    created_by   VARCHAR(200) NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    expires_on   DATE         NOT NULL,
    redeemed_by  BIGINT REFERENCES app_user (id),
    redeemed_at  TIMESTAMP
);

CREATE TABLE parent_link (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id  BIGINT    NOT NULL REFERENCES app_user (id),
    child_id   BIGINT    NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    linked_at  TIMESTAMP NOT NULL,
    UNIQUE (parent_id, child_id)
);

CREATE TABLE home_activity (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage             VARCHAR(20)  NOT NULL,
    position          INT          NOT NULL,
    title             VARCHAR(200) NOT NULL,
    focus             VARCHAR(500) NOT NULL,
    duration_minutes  INT          NOT NULL,
    video_url         VARCHAR(500),
    status            VARCHAR(20)  NOT NULL,
    reviewed_by       VARCHAR(200),
    reviewed_at       TIMESTAMP,
    UNIQUE (stage, position)
);

CREATE TABLE home_activity_step (
    activity_id  BIGINT       NOT NULL REFERENCES home_activity (id) ON DELETE CASCADE,
    position     INT          NOT NULL,
    description  VARCHAR(300) NOT NULL,
    PRIMARY KEY (activity_id, position)
);

CREATE TABLE guidance_article (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(200)  NOT NULL,
    summary          VARCHAR(500)  NOT NULL,
    body             VARCHAR(8000) NOT NULL,
    stage            VARCHAR(20),
    minutes_to_read  INT           NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    reviewed_by      VARCHAR(200),
    reviewed_at      TIMESTAMP
);

-- The parent's own record. Not shown to the school.
CREATE TABLE home_session_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    VARCHAR(64) NOT NULL UNIQUE,
    parent_id    BIGINT      NOT NULL REFERENCES app_user (id),
    child_id     BIGINT REFERENCES child (id) ON DELETE SET NULL,
    activity_id  BIGINT      NOT NULL REFERENCES home_activity (id),
    stage        VARCHAR(20) NOT NULL,
    done_on      DATE        NOT NULL
);
CREATE INDEX idx_home_record_parent ON home_session_record (parent_id, done_on);
