-- One film for every session of a colour's rhyme or module (go-live task 57). It is kept here, not on the sessions,
-- so it also applies to sessions of that unit added later, as when the session plans load. A session's own film wins.
CREATE TABLE unit_film (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage       VARCHAR(20)  NOT NULL,
    unit        INT          NOT NULL,
    video_url   VARCHAR(500),
    video_key   VARCHAR(200),
    credit      VARCHAR(200),
    attached_by VARCHAR(255) NOT NULL,
    attached_at TIMESTAMP    NOT NULL,
    CONSTRAINT uq_unit_film UNIQUE (stage, unit)
);
