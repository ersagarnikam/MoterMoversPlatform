-- Live course sessions run on Zoom inside the platform. Each cohort now has a start time, and its live
-- sessions are dated (weekly from the start date, one per live session of the course). Attendance is a
-- register per session; enrolment.sessions_attended stays as the count the certificate rule reads.

ALTER TABLE cohort ADD COLUMN start_time TIME NOT NULL DEFAULT '19:00:00';

CREATE TABLE cohort_session (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_id         BIGINT       NOT NULL REFERENCES cohort (id) ON DELETE CASCADE,
    number            INT          NOT NULL CHECK (number > 0),
    starts_at         TIMESTAMP    NOT NULL,
    duration_minutes  INT          NOT NULL CHECK (duration_minutes > 0),
    -- Set when the Zoom meeting is first needed (someone starts or joins the session).
    zoom_meeting_id   VARCHAR(30),
    zoom_passcode     VARCHAR(20),
    UNIQUE (cohort_id, number)
);

CREATE TABLE session_attendance (
    session_id    BIGINT       NOT NULL REFERENCES cohort_session (id) ON DELETE CASCADE,
    enrolment_id  BIGINT       NOT NULL REFERENCES enrolment (id) ON DELETE CASCADE,
    marked_by     VARCHAR(200) NOT NULL,
    marked_at     TIMESTAMP    NOT NULL,
    PRIMARY KEY (session_id, enrolment_id)
);

CREATE INDEX idx_session_attendance_enrolment ON session_attendance (enrolment_id);
