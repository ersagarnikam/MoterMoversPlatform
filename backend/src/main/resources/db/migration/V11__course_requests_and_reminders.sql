-- School staff ask for a place on a paid course; their head approves it before the school is invoiced. Approving
-- books the place (an enrolment) and adds the school's payment; declining or withdrawing books nothing.
CREATE TABLE course_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_id     BIGINT       NOT NULL REFERENCES cohort (id) ON DELETE CASCADE,
    user_id       BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    school_id     BIGINT       NOT NULL REFERENCES school (id) ON DELETE CASCADE,
    status        VARCHAR(20)  NOT NULL,
    requested_at  TIMESTAMP    NOT NULL,
    decided_by    VARCHAR(200),
    decided_at    TIMESTAMP
);
CREATE INDEX idx_course_request_school ON course_request (school_id, status);
CREATE INDEX idx_course_request_user ON course_request (user_id);

-- The payment raised for a place (a school's invoice for staff), so cancelling the place cancels it while due.
ALTER TABLE enrolment ADD COLUMN payment_id BIGINT REFERENCES payment (id) ON DELETE SET NULL;

-- When the reminder email for a live session went out, so it goes once.
ALTER TABLE cohort_session ADD COLUMN reminder_sent_at TIMESTAMP;
