-- Motor Movers platform: initial schema.
-- Children are stored by initials and year group only; full names are opt-in per school.

CREATE TABLE trust (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(200) NOT NULL
);

CREATE TABLE school (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(200) NOT NULL,
    trust_id              BIGINT REFERENCES trust (id),
    region                VARCHAR(10)  NOT NULL,
    full_names_enabled    BOOLEAN      NOT NULL DEFAULT FALSE,
    video_enabled         BOOLEAN      NOT NULL DEFAULT FALSE,
    trust_can_see_children BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE TABLE licence (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id   BIGINT      NOT NULL REFERENCES school (id),
    plan        VARCHAR(30) NOT NULL,
    starts_on   DATE        NOT NULL,
    ends_on     DATE        NOT NULL
);

CREATE TABLE licence_stage (
    licence_id  BIGINT      NOT NULL REFERENCES licence (id) ON DELETE CASCADE,
    stage       VARCHAR(20) NOT NULL,
    PRIMARY KEY (licence_id, stage)
);

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(200) NOT NULL UNIQUE,
    display_name   VARCHAR(200) NOT NULL,
    password_hash  VARCHAR(200) NOT NULL,
    role           VARCHAR(30)  NOT NULL,
    school_id      BIGINT REFERENCES school (id),
    trust_id       BIGINT REFERENCES trust (id)
);

CREATE TABLE school_class (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id    BIGINT       NOT NULL REFERENCES school (id),
    name         VARCHAR(100) NOT NULL,
    year_group   VARCHAR(30)  NOT NULL,
    teacher_id   BIGINT REFERENCES app_user (id),
    stage        VARCHAR(20)  NOT NULL
);

CREATE TABLE child (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_class_id BIGINT      NOT NULL REFERENCES school_class (id),
    initials        VARCHAR(10) NOT NULL,
    full_name       VARCHAR(200),
    year_group      VARCHAR(30) NOT NULL,
    starting_stage  VARCHAR(20),
    current_stage   VARCHAR(20),
    video_consent   BOOLEAN     NOT NULL DEFAULT FALSE,
    left_on         DATE,
    created_at      TIMESTAMP   NOT NULL
);

CREATE TABLE child_access_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id    BIGINT       NOT NULL,
    school_id   BIGINT       NOT NULL,
    user_email  VARCHAR(200) NOT NULL,
    action      VARCHAR(50)  NOT NULL,
    at          TIMESTAMP    NOT NULL
);
CREATE INDEX idx_access_log_child ON child_access_log (child_id);

CREATE TABLE programme_session (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage             VARCHAR(20)  NOT NULL,
    unit              INT          NOT NULL,
    day_number        INT          NOT NULL,
    title             VARCHAR(200) NOT NULL,
    focus             VARCHAR(500) NOT NULL,
    duration_minutes  INT          NOT NULL,
    video_url         VARCHAR(500),
    status            VARCHAR(20)  NOT NULL,
    reviewed_by       VARCHAR(200),
    reviewed_at       TIMESTAMP,
    UNIQUE (stage, unit, day_number)
);

CREATE TABLE programme_session_activity (
    session_id  BIGINT       NOT NULL REFERENCES programme_session (id) ON DELETE CASCADE,
    position    INT          NOT NULL,
    description VARCHAR(300) NOT NULL,
    PRIMARY KEY (session_id, position)
);

CREATE TABLE daily_session_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_class_id  BIGINT       NOT NULL REFERENCES school_class (id),
    session_id       BIGINT       NOT NULL REFERENCES programme_session (id),
    session_date     DATE         NOT NULL,
    present_count    INT          NOT NULL,
    absent_count     INT          NOT NULL,
    completed_by     VARCHAR(200) NOT NULL,
    UNIQUE (school_class_id, session_date)
);

CREATE TABLE screening_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(50)  NOT NULL UNIQUE,
    position      INT          NOT NULL,
    area          VARCHAR(40)  NOT NULL,
    title         VARCHAR(200) NOT NULL,
    instructions  VARCHAR(500) NOT NULL
);

CREATE TABLE screening_item_level (
    item_id      BIGINT       NOT NULL REFERENCES screening_item (id) ON DELETE CASCADE,
    score        INT          NOT NULL,
    description  VARCHAR(200) NOT NULL,
    PRIMARY KEY (item_id, score)
);

CREATE TABLE screening_result (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     VARCHAR(64)  NOT NULL UNIQUE,
    child_id      BIGINT       NOT NULL REFERENCES child (id) ON DELETE CASCADE,
    item_id       BIGINT       NOT NULL REFERENCES screening_item (id),
    round_number  INT          NOT NULL,
    score         INT          NOT NULL,
    screened_on   DATE         NOT NULL,
    recorded_by   VARCHAR(200) NOT NULL
);
CREATE INDEX idx_screening_child ON screening_result (child_id);

CREATE TABLE course (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track              VARCHAR(20)  NOT NULL,
    title              VARCHAR(200) NOT NULL,
    description        VARCHAR(1000) NOT NULL,
    live_sessions      INT          NOT NULL,
    session_minutes    INT          NOT NULL,
    price_pence        INT          NOT NULL,
    renewal_pence      INT,
    awards_certificate BOOLEAN      NOT NULL
);

CREATE TABLE cohort (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id          BIGINT       NOT NULL REFERENCES course (id),
    name               VARCHAR(100) NOT NULL,
    starts_on          DATE         NOT NULL,
    time_slot          VARCHAR(100) NOT NULL,
    capacity           INT          NOT NULL,
    trainer_name       VARCHAR(200) NOT NULL,
    recording_agreed   BOOLEAN      NOT NULL
);

CREATE TABLE enrolment (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_id              BIGINT    NOT NULL REFERENCES cohort (id),
    user_id                BIGINT    NOT NULL REFERENCES app_user (id),
    enrolled_at            TIMESTAMP NOT NULL,
    sessions_attended      INT       NOT NULL DEFAULT 0,
    assessment_passed      BOOLEAN   NOT NULL DEFAULT FALSE,
    certificate_issued_on  DATE,
    certificate_expires_on DATE,
    UNIQUE (cohort_id, user_id)
);
